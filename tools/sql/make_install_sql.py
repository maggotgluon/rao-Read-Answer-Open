#!/usr/bin/env python3
"""
Build database/sql/rao-install-<version>.sql: a full first-install for hosts that cannot run
artisan (import it once with phpMyAdmin). Stdlib only.
สร้างไฟล์ SQL สำหรับติดตั้งครั้งแรก บนโฮสต์ที่รัน artisan ไม่ได้ (นำเข้าด้วย phpMyAdmin)

Steps (a throwaway local MySQL, never the real server):
  1. CREATE DATABASE rao_install … on a local MySQL 5.7/8 with explicit_defaults_for_timestamp=ON
  2. DB_CONNECTION=mysql DB_DATABASE=rao_install … php artisan migrate --force
     … php artisan db:seed --class=PromptLibrarySeeder --force
  3. python3 tools/sql/make_install_sql.py --port 33070 --database rao_install

Schema for every table; data only for `migrations` (so later migrations know where to start)
and `prompts` (the question library). No users, no secrets.
"""

from __future__ import annotations

import argparse
import re
import subprocess
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA_TABLES = ["migrations", "prompts"]


def version() -> str:
    log = (ROOT / "resources/changelog/en.md").read_text()
    m = re.search(r"^##\s*\[([^\]]+)\]", log, re.M)
    return m.group(1) if m else "0.0.0"


def dump(args, *extra: str, tables: list[str] | None = None) -> str:
    cmd = [
        args.mysqldump, f"-h{args.host}", f"-P{args.port}", f"-u{args.user}",
        "--single-transaction", "--skip-add-locks", "--skip-lock-tables", "--no-tablespaces",
        "--skip-comments", "--skip-dump-date", "--default-character-set=utf8mb4",
        "--set-gtid-purged=OFF", *extra, args.database, *(tables or []),
    ]
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def portable(sql: str) -> str:
    """
    Make the dump import on MySQL 5.7, 8.x and MariaDB 10.x alike.
    ให้ไฟล์นำเข้าได้ทั้ง MySQL 5.7/8 และ MariaDB 10.x
    """
    # NOT NULL timestamps without a default fail on servers where
    # explicit_defaults_for_timestamp is OFF (older MariaDB). The app always sets them.
    # timestamp ที่ห้ามว่างแต่ไม่มีค่าเริ่มต้น จะ error บน MariaDB รุ่นเก่า
    sql = re.sub(
        r"(`\w+` timestamp(?:\(\d\))? NOT NULL)(?! DEFAULT)(,?\n)",
        r"\1 DEFAULT CURRENT_TIMESTAMP\2",
        sql,
    )
    # MySQL 8-only collation names, in case the dump came from MySQL 8.
    sql = sql.replace("utf8mb4_0900_ai_ci", "utf8mb4_unicode_ci")
    return sql


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", default="3306")
    ap.add_argument("--user", default="root")
    ap.add_argument("--database", default="rao_install")
    ap.add_argument("--mysqldump", default="mysqldump")
    args = ap.parse_args()

    v = version()
    schema = portable(dump(args, "--no-data", "--skip-add-drop-table"))
    schema = schema.replace("CREATE TABLE `", "CREATE TABLE IF NOT EXISTS `")
    schema = re.sub(r" AUTO_INCREMENT=\d+", "", schema)
    data = dump(args, "--no-create-info", "--skip-extended-insert", "--complete-insert", tables=DATA_TABLES)
    data = data.replace("INSERT INTO `", "INSERT IGNORE INTO `")

    head = f"""-- ─────────────────────────────────────────────────────────────────────────────
-- Rao (เรา) {v}: first install for MySQL 5.7+/8.x or MariaDB 10.3+   ({date.today()})
-- Import ONCE into an EMPTY database with phpMyAdmin → Import (utf8mb4).
-- นำเข้าครั้งเดียว ในฐานข้อมูลว่าง ผ่าน phpMyAdmin → Import
--
-- Contains: all tables, the migrations list, and the prompt library. No users, no secrets.
-- Later updates: open https://<your-domain>/_ops/migrate?token=… (see docs/deploy.md).
-- อัปเดตครั้งต่อไป: เปิดลิงก์ /_ops/migrate ตามคู่มือ docs/deploy.md
-- Generated by tools/sql/make_install_sql.py, do not edit by hand.
-- ─────────────────────────────────────────────────────────────────────────────

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';
SET time_zone = '+00:00';

"""
    tail = "\nSET FOREIGN_KEY_CHECKS = 1;\n"
    out = ROOT / "database" / "sql" / f"rao-install-{v}.sql"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(head + "-- ── Tables / ตาราง ──\n" + schema + "\n-- ── Data / ข้อมูล ──\n" + data + tail)
    print(out.relative_to(ROOT), f"{out.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
